def language_of(config) -> str:
    """Return the canonical configured language, falling back safely to English."""
    value = str(config.get("general.language", "en") or "en").strip().replace("_", "-")
    if value in LANGUAGES:
        return value
    lowered = value.lower()
    canonical = _LANGUAGE_ALIASES.get(lowered)
    return canonical if canonical in LANGUAGES else "en"


def tr(config, key: str, **kwargs) -> str:
    """Translate a launcher string for the configured language."""
    language = language_of(config)
    template = _STRINGS.get(language, {}).get(key) or _STRINGS["en"].get(key, key)
    if kwargs:
        try:
            return template.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            return template
    return template


